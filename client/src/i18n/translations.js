Object.keys(extraUi).forEach((lang) => {
  if (translations[lang]) {
    translations[lang] = deepMerge(translations[lang], extraUi[lang]);
  }
});

function getNested(obj, keys) {
  let value = obj;
  for (const k of keys) {
    if (value && typeof value === 'object' && k in value) {
      value = value[k];
    } else {
      return undefined;
    }
  }
  return typeof value === 'string' ? value : undefined;
}

// Helper function to get nested translation
export function getTranslation(language, key) {
  const keys = key.split('.');
  const primary = getNested(translations[language], keys);
  if (primary) return primary;
  if (language !== 'en-IN') {
    const en = getNested(translations['en-IN'], keys);
    if (en) return en;
  }
  if (language !== 'hi-IN') {
    const hi = getNested(translations['hi-IN'], keys);
    if (hi) return hi;
  }
  return key;
}
